def qtypes_text() -> str:
    out: list[str] = []
    for q in EXAM_QTYPES:
        out.append(
            f"【{q['name']}】\n"
            f"  常见问法：{q['ask']}\n"
            f"  答案在哪：{q['where']}\n"
            f"  正确项特征：{q['right']}\n"
            f"  干扰项怎么设：{q['traps']}"
        )
    return "\n".join(out)


def locations_text() -> str:
    return "\n".join(f"· {name}：{desc}" for name, desc in SET_POINT_LOCATIONS)


def traps_text() -> str:
    return "\n".join(f"{i+1}. {name}——{desc}（识别动作：{how}）"
                     for i, (name, desc, how) in enumerate(TRAP_PATTERNS))


def sources_text() -> str:
    return (
        "常见题源：" + "、".join(SOURCES["刊物"]) + "\n"
        f"话题倾向：{SOURCES['话题倾向']}\n"
        "语料特征（写作时要模仿这些）：\n"
        + "\n".join(f"  · {x}" for x in SOURCES["语料特征"])
    )


def patterns_text() -> str:
    return "\n\n".join(f"《{k}》{v}" for k, v in ARTICLE_PATTERNS.items())


def topic_argument_bank(topic: str) -> str:
    """取某一类话题的典型论点库；话题对不上时给全部类目名做提示。"""
    for k, v in TOPIC_MATRIX.items():
        if k == topic or k in topic or topic in k:
            return "【这一类话题的典型争论点（选 1-2 个切入，别贪多）】\n" + \
                   "\n".join(f"  · {x}" for x in v)
    return ""


def topic_index_text() -> str:
    lines = []
    for k, v in TOPIC_MATRIX.items():
        lines.append(f"· {k}：{v[0]}")
    return "\n".join(lines)


def analysis_knowledge_text() -> str:
    """注入「精读解析」这一步的命题规律。"""
    return f"""【考研英语一命题规律——你必须在分析里用上这些，不许泛泛而谈】

一、六大题型的命题手法
{qtypes_text()}

二、出题人爱在哪里设题
{locations_text()}

三、干扰项六种套路
{traps_text()}

{CORE_RULE}

{GROUNDING_RULE}
"""


def set_point_planting_text() -> str:
    """给「文章生成」用的设题点植入清单。

    出题人不是在随便哪句设题。写文章时如果不主动在这些位置留题眼，
    文章读起来再地道，也只是「一篇好文章」，做不成真题。
    这里从 SET_POINT_LOCATIONS 派生，保持单一来源——改了源表这里自动跟着变。
    """
    lines = [
        "出题人不会在随便哪句设题，命中率最高的是下面这些位置。"
        "写文章时请**主动**在这些位置留下清晰、可考的「题眼」——"
        "让关键信息天然落在这里，而不是靠堆生僻词制造难度：",
    ]
    for name, desc in SET_POINT_LOCATIONS:
        parts = [p.strip() for p in desc.split("。") if p.strip()]
        head = parts[0]
        tail = "".join(p + "。" for p in parts[1:])
        line = f"  · {name}：{head}。"
        if tail:
            line += f"（{tail}）"
        lines.append(line)
    lines.append("")
    lines.append(CORE_RULE)
    lines.append(
        "落到写法上：**关键立场别写成一句大白话**——"
        "把它放进带让步、带限定、带修饰的句子里，"
        "同时保证它**在原文里推得出来**，不是含糊其辞。"
        "还要刻意让一两处的正确说法与原文**不同词**，"
        "好让「同义改写」这条规律真的成立。"
    )
    return "\n".join(lines)


def article_knowledge_text(topic: str) -> str:
    """注入「文章生成」这一步的题源与篇章要求。"""
    bank = topic_argument_bank(topic)
    return f"""【真题题源画像——请让文章读起来像这一类刊物的文章】
{sources_text()}

【话题落点】
{topic_index_text()}
{bank}

【篇章模式——本篇请采用其中一种，写出真题那种「有争论、有层次」的感觉】
{patterns_text()}

【设题点植入清单——出题人会盯住这些地方】
{set_point_planting_text()}
"""
